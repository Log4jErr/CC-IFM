def read_text(path):
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()

VERSION_SITES = (
    ("modules/transfer.lua", r'(Transfer\.VERSION = ")([^"]+)(")'),
    ("IFMMaster.lua", r'(local IFM_VERSION = ")([^"]+)(")'),
    ("web/ifm-core.js", r"(IFM_CLIENT_VERSION = ')([^']+)(')"),
    ("web/ifm-app.js", r"(IFM_APP_BUILD = ')([^']+)(')"),
)

def repo_root(base_dir):
    return os.path.dirname(os.path.abspath(base_dir))

def site_path(base_dir, rel):
    if rel.startswith("web/"):
        return os.path.join(repo_root(base_dir), "frontend", rel.replace("/", os.sep))
    return os.path.join(base_dir, rel.replace("/", os.sep))

def read_required(path):
    if not os.path.isfile(path):
        raise SystemExit("找不到文件：%s（构建需要完整的 backend/ 与 frontend/）" % path)
    return read_text(path)

def parse_version(value):
    text = str(value).strip()
    if not re.fullmatch(r"\d+", text):
        raise SystemExit("版本号必须是单一整数（例如 --version 306），不再支持点分格式：%r" % value)
    return int(text)

def read_version(base_dir):
    repo = repo_root(base_dir)
    found = []
    legacy = []
    for rel, pattern in VERSION_SITES:
        path = site_path(base_dir, rel)
        match = re.search(pattern, read_required(path))
        if not match:
            raise SystemExit("找不到版本号：%s（期望形如 ... = \"12\" 的整数）" % path)
        raw = match.group(2)
        if re.fullmatch(r"\d+", raw):
            found.append((os.path.relpath(path, repo), int(raw)))
        else:
            legacy.append((os.path.relpath(path, repo), raw))
    index_path = os.path.join(repo, "frontend", "index.html")
    index = read_required(index_path)
    build = re.search(r'data-ifm-build="(\d+)"', index)
    if not build:
        raise SystemExit("找不到 data-ifm-build：%s" % index_path)
    tags = re.findall(r"\?v=(\d+)", index)
    if not tags:
        raise SystemExit("index.html 里找不到任何 ?v=<数字>：%s" % index_path)
    if len(set(tags) | {build.group(1)}) != 1:
        raise SystemExit("index.html 里的版本号不一致：data-ifm-build=%s，?v=%s"
                         % (build.group(1), ",".join(sorted(set(tags)))))
    found.append((os.path.relpath(index_path, repo), int(build.group(1))))
    for rel, raw in legacy:
        print("提示：%s 还是点分版本号 %s，本次构建会统一成整数" % (rel, raw))
    current = max(value for _, value in found)
    if len({value for _, value in found}) != 1:
        print("版本号不一致：%s —— 以最大值 %d 为准并统一写回"
              % ("、".join("%s=%d" % item for item in found), current))
    return current

def write_version(base_dir, version):
    repo = repo_root(base_dir)
    text = str(parse_version(version))
    for rel, pattern in VERSION_SITES:
        path = site_path(base_dir, rel)
        content = read_required(path)
        updated, count = re.subn(pattern, lambda match: match.group(1) + text + match.group(3), content)
        if count != 1:
            raise SystemExit("版本号写入失败（%s，匹配 %d 次）" % (path, count))
        if updated != content:
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(updated)
    index_path = os.path.join(repo, "frontend", "index.html")
    index = read_required(index_path)
    updated, build_count = re.subn(r'data-ifm-build="\d+"', 'data-ifm-build="%s"' % text, index)
    if build_count != 1:
        raise SystemExit("data-ifm-build 写入失败（%s，匹配 %d 次）" % (index_path, build_count))
    updated, tag_count = re.subn(r"\?v=\d+", "?v=%s" % text, updated)
    if tag_count == 0:
        raise SystemExit("index.html 里的 ?v= 版本号写入失败：%s" % index_path)
    if updated != index:
        with open(index_path, "w", encoding="utf-8", newline="") as handle:
            handle.write(updated)
    print("版本号：%s（transfer.lua / IFMMaster.lua / ifm-core.js / ifm-app.js 各 1 处，"
          "index.html 的 data-ifm-build 与 %d 个 ?v=）" % (text, tag_count))
    return int(text)

def collect_files(base_dir):
    modules = []
    module_dir = os.path.join(base_dir, MODULE_DIR_NAME)
    if not os.path.isdir(module_dir):
        raise SystemExit("找不到模块目录：%s" % module_dir)
    for name in sorted(os.listdir(module_dir)):
        if not name.endswith(".lua"):
            continue
        path = os.path.join(module_dir, name)
        rel = "%s/%s" % (MODULE_DIR_NAME, name)
        modules.append((rel, read_text(path)))
    if not modules:
        raise SystemExit("模块目录中没有 .lua 文件：%s" % module_dir)
    main_path = os.path.join(base_dir, MAIN_FILE_NAME)
    if not os.path.isfile(main_path):
        raise SystemExit("找不到主程序：%s" % main_path)
    main_rel = MAIN_FILE_NAME
    return modules, (main_rel, read_text(main_path))

