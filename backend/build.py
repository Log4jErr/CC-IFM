def read_text(path):
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def collect_files(base_dir):
    """返回 [(相对路径, 内容), ...]，主程序放在最后"""
    modules = []
    module_dir = os.path.join(base_dir, MODULE_DIR_NAME)
    if not os.path.isdir(module_dir):
        raise SystemExit("找不到模块目录：%s" % module_dir)
    for name in sorted(os.listdir(module_dir)):
        if not name.endswith(".lua"):
            continue
        path = os.path.join(module_dir, name)
        rel = "%s/%s" % (MODULE_DIR_NAME, name)
        modules.append((rel, read_text(path)))
    if not modules:
        raise SystemExit("模块目录中没有 .lua 文件：%s" % module_dir)
    main_path = os.path.join(base_dir, MAIN_FILE_NAME)
    if not os.path.isfile(main_path):
        raise SystemExit("找不到主程序：%s" % main_path)
    main_rel = MAIN_FILE_NAME
    return modules, (main_rel, read_text(main_path))


def collect_extra_entries(base_dir):
    """除模块与主入口之外，还要一起打进产物的**独立入口文件**（解压后即可就地启动）。
    目前是 IFMWorker.lua：worker 计算机与主控计算机用的是同一份产物，角色只由启动的入口决定。"""
