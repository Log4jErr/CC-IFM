def bracket_level_for(content):
    """根据内容选择合适的长括号等级，避免与内容里的 ]==] 冲突"""
    level = 1
    for match in re.finditer(r"\](=*)\]", content):
        level = max(level, len(match.group(1)) + 1)
    for match in re.finditer(r"\[(=*)\[", content):
        level = max(level, len(match.group(1)) + 1)
    return level


