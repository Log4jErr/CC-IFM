def render_entries(files):
    chunks = []
    for rel, content in files:
        level = bracket_level_for(content)
        opener = "[" + "=" * level + "["
        closer = "]" + "=" * level + "]"
        chunks.append('    ["%s"] = %s\n%s%s,\n' % (rel, opener, content, closer))
    return "".join(chunks)


