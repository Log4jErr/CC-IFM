def vendor_dir_path(base_dir):
    return os.path.join(base_dir, *VENDOR_DIR_NAME.split("/"))

def read_vendor(base_dir):
    directory = vendor_dir_path(base_dir)
    missing = [name for name in VENDOR_FILES if not os.path.isfile(os.path.join(directory, name))]
    if missing:
        raise SystemExit("缺少 vendored zzlib 文件：%s（见 %s/UPSTREAM.txt）" %
                         (", ".join(missing), directory))
    out = {}
    for name in VENDOR_FILES:
        with open(os.path.join(directory, name), "r", encoding="utf-8", newline="\n") as handle:
            text = handle.read()
        try:
            text.encode("ascii")
        except UnicodeEncodeError:
            raise SystemExit("vendored 文件必须是纯 ASCII（CC:T 端原样执行）：%s" % name)
        out[name] = text
    return out

def render_archive(files):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for rel, content in files:
            archive.writestr(rel, content.encode("utf-8"))
    blob = buffer.getvalue()
    encoded = base64.b64encode(blob).decode("ascii")
    with zipfile.ZipFile(io.BytesIO(blob)) as check:
        names = check.namelist()
        expected = [rel for rel, _ in files]
        if names != expected:
            raise SystemExit("载荷自检失败：ZIP 条目与源码不一致（%s）" % names)
        for rel, content in files:
            if check.read(rel) != content.encode("utf-8"):
                raise SystemExit("载荷自检失败：ZIP 内容与源码不一致：%s" % rel)
    print("载荷自检：ZIP 内 %d 个文件与源码逐字节一致（%d 字节 -> base64 %d 字符）" %
          (len(files), len(blob), len(encoded)))
    segments = [encoded[i:i + ARCHIVE_SEGMENT_CHARS]
                for i in range(0, len(encoded), ARCHIVE_SEGMENT_CHARS)]
    lines = ["local __IFM_ARCHIVE = table.concat({"]
    for segment in segments:
        lines.append("[[%s]]," % segment)
    lines.append("})")
    return "\n".join(lines) + "\n", len(blob), len(encoded)

