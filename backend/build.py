def run_tools_check(base_dir):
    """检查 tools/*.lua（netsync / netserver / crafter 这些单独运行的脚本）。

    它们不参与打包，但同样要守规矩（用户第 4 项要求）：
      * 代码与字符串只允许 ASCII —— 脚本把提示 print 到 CC 终端，终端字形没有中日韩字符，
        而且 \\uXXXX 转义在 CC:T 的 Lua 5.1 下不会被还原（会原样打印），所以这里必须写英文；
      * 语法必须是合法的 Lua 5.1（这些脚本运行时没有 bundle 兜底，一报错就整台机器卡住）。
    """
    tool_dir = os.path.join(base_dir, "tools")
    if not os.path.isdir(tool_dir):
        return
    files = [("tools/" + name, read_text(os.path.join(tool_dir, name)))
             for name in sorted(os.listdir(tool_dir)) if name.endswith(".lua")]
    if not files:
        return
    ascii_source = load_ascii_checker()
    problems = []
    for rel, content in files:
        bad = ascii_source.find_violations(content)
        if not bad:
            continue
        problems.append("%s: %d 处非 ASCII（代码/字符串）" % (rel, len(bad)))
        for line, col, ch, kind in bad[:5]:
            problems.append("    第 %d 行第 %d 列 [%s] %r" % (line, col, ch, kind))
        if len(bad) > 5:
            problems.append("    ...（其余 %d 处省略）" % (len(bad) - 5))
    if problems:
        raise SystemExit(
            "构建中止：tools/ 下的脚本是单独运行、直接 print 到 CC 终端的，"
            "代码与字符串只允许 ASCII（注释不受限）。\n"
            "请把这些提示写成英文，不要用 \\uXXXX 转义（Lua 5.1 不会还原，会原样打印）：\n"
            + "\n".join(problems))
    print("tools 检查：通过（%d 个独立脚本，代码与字符串均为 ASCII）" % len(files))
    run_lua_syntax_check(files, base_dir)


def run_ascii_check(files, fix=False):
    """ASCII 检查（代码/字符串必须是 ASCII）——构建流程的强制步骤。

    返回检查结果说明；有违例且 fix=False 时直接中止构建。
    """
    ascii_source = load_ascii_checker()
    fixed = 0
    if fix:
        for rel, content in files:
            bad = ascii_source.find_violations(content)
            if not bad:
                continue
            converted = ascii_source.convert(content)
            if converted != content:
                path = os.path.join(BASE_DIR_HACK[0], rel.replace("/", os.sep))
                with open(path, "w", encoding="utf-8", newline="") as handle:
                    handle.write(converted)
                fixed += len(bad)
                print("  - 自动转换 %s：%d 处非 ASCII → \\uXXXX" % (rel, len(bad)))
        if fixed:
            files = [(rel, read_text(os.path.join(BASE_DIR_HACK[0], rel.replace("/", os.sep)))) for rel, _ in files]
            print("ASCII 检查：已自动修正 %d 处，源码已重新读取" % fixed)

    problems = []
    for rel, content in files:
        bad = ascii_source.find_violations(content)
        if not bad:
            continue
        problems.append("%s：%d 处非 ASCII（代码/字符串）" % (rel, len(bad)))
        for line, col, ch, kind in bad[:5]:
            problems.append("    第 %d 行第 %d 列 [%s] %r" % (line, col, kind, ch))
        if len(bad) > 5:
            problems.append("    ...（其余 %d 处省略）" % (len(bad) - 5))
    if problems:
        raise SystemExit(
            "构建中止：Lua 源码的代码/字符串部分只允许 ASCII，注释不受限。\n"
            "字符串里的中文请写成 \\uXXXX 字面转义，或直接运行：python build.py --fix-ascii\n"
            + "\n".join(problems)
        )
    print("ASCII 检查：通过（%d 个 Lua 文件，代码与字符串均为 ASCII）" % len(files))
    return files


def build_bundle(base_dir, output_path, keep_comments=False, fix_ascii=False):
    BASE_DIR_HACK[0] = base_dir
    modules, main_entry = collect_files(base_dir)
    # 主入口也一并内嵌：运行时会被解压回磁盘，便于以后直接运行 IFMMaster.lua
    # 额外入口（IFMWorker.lua）也打进去：同一台计算机的角色只取决于启动哪个入口
    extras = collect_extra_entries(base_dir)
    files = list(modules) + [main_entry] + extras
    # 构建流程内强制做 ASCII 检查（必要时可自动修正并继续）
    files = run_ascii_check(files, fix_ascii)
    # 检查“局部变量先用后声明”（运行时是 nil 全局，会让整包快照推送失败）
    files = run_local_order_check(files)
    # 再检查“保留字当字段名/表键”（Lua 5.1 语法错误，只有 load 时才暴露）
    files = run_reserved_word_check(files)
    # 最后检查“实例字段有没有把类方法遮蔽掉”（运行时报 attempt to call method 'x'）
    files = run_method_shadow_check(files)
    # Lua 语法检查（方法调用参数 / 块结构 / 字符串收尾）：本机没有 lua 可执行文件，这里是轻量替代
    files = run_lua_syntax_check(files)
    # tools/ 下的脚本是单独运行的（不进 bundle），但也要过 ASCII 与语法检查：
    # 它们直接 print 到 CC 终端，字符串里的非 ASCII 会变成乱码（用户第 4 项要求）。
    run_tools_check(base_dir)
    raw_size = sum(len(content.encode("utf-8")) for _, content in files)
    extra_count = len(extras)
    if not keep_comments:
        # 默认剥离全部注释（所有内嵌文件，包括 IFMWorker.lua）：中文注释是产物体积的大头，
        # CC:T 磁盘放不下就会报 “ifm_bundle: out of space”。注释只影响可读性，不影响运行。
        files = [(rel, strip_comments(content)) for rel, content in files]
        # 再删掉每行行首缩进（Lua 不在乎缩进，但光缩进就有几十 KB —— 小磁盘上不值得）
        files = [(rel, strip_line_indentation(content)) for rel, content in files]
        # 剥离后的源码必须仍然是合法 Lua（防止剥离器误伤字符串 / 长字符串）：再过一遍语法检查
        files = run_lua_syntax_check(files)
    # 报告用：按顺序切回「模块 / 主入口 / 额外入口」
    modules = files[:len(files) - 1 - extra_count]
    main_entry = files[len(files) - 1 - extra_count]
    stripped_size = sum(len(content.encode("utf-8")) for _, content in files)
    digest = hashlib.sha256()
    for rel, content in files:
        digest.update(rel.encode("utf-8"))
        digest.update(content.encode("utf-8"))
    parts = [
        HEADER.format(
            built_at=time.strftime("%Y-%m-%d %H:%M:%S"),
            digest=digest.hexdigest()[:16],
        ),
        BOOTSTRAP_TEMPLATE.format(
            module_dir=MODULE_DIR_NAME,
            main=MAIN_FILE_NAME,
            worker=WORKER_FILE_NAME,
            crafter=CRAFTER_FILE_NAME,
            entries=render_entries(files),
        ),
    ]
    # 注意：不再把主入口内容追加到产物末尾 —— 产物只负责解压（+ 自我删除），不自启服务端。
    bundle = "".join(parts)
    out_dir = os.path.dirname(os.path.abspath(output_path))
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    with open(output_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(bundle)
    return files, len(bundle), raw_size, stripped_size


def strip_line_indentation(content):
    """删掉每行**行首**的空白（行尾空白留给 strip_comments 处理），字符串里的内容一字不动。

    为什么：Lua 不在乎缩进，而深度缩进的模块每行要花 4~12 个空格 —— 18 个文件加起来是
    几十 KB，在 CC:T 的小磁盘上（默认 1MB，还要放 config.json / cache.json）非常不值得。
    换行符保留（行号不变，报错行号仍然对得上源码），只丢缩进。

    安全性：与 strip_comments 一样是 Lua 感知的 —— [[...]] 长字符串/长注释整段原样复制，
    '...' / "..." 短字符串也原样复制（里面的前导空格有语义）。剥离后构建会再跑一遍 luaparse，
    一旦误伤字符串会立刻报错中止。
    """
    out = []
    index = 0
    size = len(content)
    at_line_start = True
    while index < size:
        match = LONG_BRACKET.match(content, index)
        if match:
            end = long_bracket_end(content, index, match.group(1))
            out.append(content[index:end])
            at_line_start = content[end - 1:end] == "\n"
            index = end
            continue
        char = content[index]
        if char == "\n":
            out.append(char)
            at_line_start = True
            index += 1
            continue
        if at_line_start and (char == " " or char == "\t"):
            index += 1                          # 行首缩进直接丢掉
            continue
        at_line_start = False
        if char in "\"'":
            end = scan_short_string(content, index)
            out.append(content[index:end])
            index = end
            continue
        out.append(char)
        index += 1
    return "".join(out)


def strip_comments(content):
    """删掉 Lua 源码里所有注释（行注释 `--` 与块注释 `--[[ ]]`），保留其余内容与行数。

    为什么要这么做：模块里有大量中文注释（UTF-8 三个字节一个字），一起打进产物会让产物
    体积翻倍 —— CC:Tweaked 计算机的磁盘很小（默认 1MB），产物会直接写不进去
    （"ifm_bundle: out of space"）。注释是给读源码的人看的，跑起来不需要：
    产物解压出来的源码因此没有注释；要看注释请直接用仓库里的 backend/ 源码。

    正确处理（绝不会误伤代码）：
      * 短字符串 '...' / "..."（含 \\ 转义）；
      * 长字符串 [[...]] / [=[...]=]：Lua 里这是代码，原样保留；
      * 整行注释与行尾注释；
      * 块注释里的换行保留 —— 行号基本不变，产物里的报错仍然对得上源码；
      * 注释删掉后行尾留下的空白也一并清掉（产物更小），但绝不会动字符串内部。
    """
    parts = []
    index = 0
    size = len(content)
    last_was_string = False
    while index < size:
        char = content[index]
        if char in ("'", '"'):
            end = scan_short_string(content, index)
            parts.append(content[index:end])
            index = end
            last_was_string = True
            continue
        if char == "[":
            match = LONG_BRACKET.match(content, index)
            if match:
                end = long_bracket_end(content, index, match.group(1))
                parts.append(content[index:end])
                index = end
                last_was_string = True
                continue
            parts.append(char)
            index += 1
            last_was_string = False
            continue
        if char == "-" and content.startswith("--", index):
            match = LONG_BRACKET.match(content, index + 2)
            if match:
                # 块注释：只留下其中的换行（行号不变）
                end = long_bracket_end(content, index + 2, match.group(1))
                parts.append(re.sub(r"[^\n]", "", content[index:end]))
                index = end
                last_was_string = True          # 保留的换行后不算“行尾空白”
                continue
            newline = content.find("\n", index)
            index = size if newline < 0 else newline
            continue
        if char == "\n":
            if not last_was_string:
                trim_trailing_blanks(parts)
            parts.append(char)
            index += 1
            last_was_string = False
            continue
        parts.append(char)
        index += 1
        last_was_string = False
    if not last_was_string:
        trim_trailing_blanks(parts)
    return "".join(parts)


LONG_BRACKET = re.compile(r"\[(=*)\[")


def long_bracket_end(content, start, equals):
    """长括号（长字符串 / 块注释）的结束位置（含收尾的 ]==]）"""
    closer = "]" + equals + "]"
    found = content.find(closer, start + 2 + len(equals))
    if found < 0:
        return len(content)                     # 没闭合（源码本身有错）：留到结尾
    return found + len(closer)


def scan_short_string(content, start):
    """短字符串的结束位置（含收尾引号），\\ 转义按两个字符跳过"""
    quote = content[start]
    index = start + 1
    size = len(content)
    while index < size:
        char = content[index]
        if char == "\\":
            index += 2
            continue
        if char == quote:
            return index + 1
        index += 1
    return size


def trim_trailing_blanks(parts):
    """清掉 `parts` 末尾的行尾空白（注释被删后留下的空格/制表符）"""
    while parts:
        last = parts[-1]
        stripped = last.rstrip(" \t")
        if stripped:
            if stripped != last:
                parts[-1] = stripped
            return
        parts.pop()


def main(argv=None):
    parser = argparse.ArgumentParser(description="IFM 单文件构建脚本")
    parser.add_argument("-o", "--out", default=None, help="输出文件路径（默认与脚本同级的 %s）" % DEFAULT_OUTPUT)
    parser.add_argument("--keep-comments", "--minify-comments-off", dest="keep_comments", action="store_true",
                        help="保留源码注释（默认会全部剥离：产物要能塞进 CC:T 的小磁盘）")
    parser.add_argument("--fix-ascii", action="store_true",
                        help="发现非 ASCII 的代码/字符串时自动转成 \\uXXXX 再继续构建（默认报错中止）")
    parser.add_argument("--version", default=None, metavar="X.Y.Z",
                        help="把版本号写到所有必须一致的地方（transfer.lua / IFMMaster.lua / web/ifm-core.js）")
    parser.add_argument("--bump", action="store_true",
                        help="网页构建戳 +1（data-ifm-build / 全部 ?v= / IFM_APP_BUILD 三处同步）")
    args = parser.parse_args(argv)

    base_dir = os.path.dirname(os.path.abspath(__file__))
    if args.version:
        set_version(base_dir, args.version)
    if args.bump:
        bump_build_stamp(base_dir)
    output_path = args.out or os.path.join(base_dir, DEFAULT_OUTPUT)
    if os.path.basename(output_path).lower() in (MAIN_FILE_NAME.lower(), WORKER_FILE_NAME.lower(),
                                                 CRAFTER_FILE_NAME.lower()):
        print("警告：产物与 %s / %s / %s 同名，运行时会被保留（不自我删除）；它本身不是入口本体，建议换个名字。" %
              (MAIN_FILE_NAME, WORKER_FILE_NAME, CRAFTER_FILE_NAME))
    files, size, raw_size, stripped_size = build_bundle(base_dir, output_path, args.keep_comments, args.fix_ascii)
    print("已生成单文件产物：%s" % output_path)
    print("内嵌文件 %d 个（含主入口）：" % len(files))
    for rel, content in files:
        print("  - %s (%d 字节)" % (rel, len(content.encode("utf-8"))))
    if not args.keep_comments:
        saved = raw_size - stripped_size
        print("注释剥离：源码 %d 字节 -> %d 字节（省下 %d 字节，%.0f%%）" %
              (raw_size, stripped_size, saved, (saved * 100.0 / raw_size) if raw_size else 0))
    print("产物总计 %d 字节（CC:T 默认磁盘 1MB，%s）" %
          (size, "放得下" if size < 1000000 else "可能放不下：请检查是否有超大文件或改用 --out 分卷"))
    print("提示：产物只解压、不自启：运行后会在同级创建 ifm/ 目录，把 IFMMaster.lua / IFMWorker.lua / "
      "IFMCrafter.lua 与 modules/*.lua 写进去，并删除产物自身；")
    print("      然后手动运行 ifm/%s [--room <房间号>] [--relay <中转地址前缀>] [--random-room] 启动服务端。" % MAIN_FILE_NAME)
    print("      其它计算机（worker / 机械臂）用同一份产物解压后，启动 ifm/%s 或 ifm/%s 即可。"
          % (WORKER_FILE_NAME, CRAFTER_FILE_NAME))
    return 0


if __name__ == "__main__":
    sys.exit(main())
