def run_global_write_check(files):
    """An identifier that is only ever *assigned* cannot stay undeclared.

    Writing to a name that is neither a `local` of that file nor a runtime global
    silently creates a global. Reading it back before the write (or after the
    declaration was deleted) then fails at runtime with
    "attempt to index global 'x' (a nil value)" - exactly the class of crash this
    check exists to catch at build time.
    """
    problems = []
    for rel, content in files:
        raw, _string_problems = strip_lua_code(content)
        code = STRING_LITERAL.sub('""', raw)
        declared = set()
        for match in LUA_LOCAL_DECL.finditer(code):
            for name in match.group(1).split(","):
                declared.add(name.strip())
        # Function parameters are locals too (assigning to `opts` is not a global).
        for match in LUA_PARAM_LIST.finditer(code):
            for name in match.group(1).split(","):
                declared.add(name.strip())
        # Loop variables and the implicit `self` of `function Class:method()`.
        for match in LUA_FOR_DECL.finditer(code):
            for name in match.group(1).split(","):
                declared.add(name.strip())
        if LUA_METHOD_DEF.search(code):
            declared.add("self")
        depth = 0
        for index, line in enumerate(code.splitlines(), 1):
            # Inside a table constructor `name = value` is a *field*, not a global
            # write: only look at statement level (brace depth 0).
            if depth == 0:
                match = LUA_GLOBAL_WRITE.match(line)
                if match:
                    name = match.group(1)
                    if name not in declared and name not in LUA_GLOBALS and name not in (
                            "end", "then", "else", "elseif", "do", "if", "for", "while",
                            "repeat", "until", "function", "local", "return", "break"):
                        problems.append("  %s:%d  %s" % (rel, index, name))
            depth += line.count("{") - line.count("}")
    if problems:
        raise SystemExit(
            "构建中止：赋值给未声明的全局变量（Lua 会静默创建全局；读回时是 nil，"
            "运行时报 attempt to index global 'x'）。\n"
            "修法：在该文件上方声明 local，或删掉这处残留引用：\n" + "\n".join(sorted(set(problems)))
        )
    print("全局变量检查：通过（%d 个 Lua 文件，没有未声明的全局赋值）" % len(files))
    return files

# Calls whose *result can be nil* (documented behaviour: "unknown / not read yet").
# Using such a result directly as an arithmetic operand is the classic master crash
# ("attempt to perform arithmetic on a nil value") because the value is only nil while
# the scan is still incomplete - i.e. exactly during warm-up, minutes after startup.
NIL_CAPABLE_CALLS = (
    "slotCapacityFor",
    "slotStackCount",
    "slotLimitOf",
    "itemMaxCount",
    "slotCount",
)

CALL = r"(?:[A-Za-z_][A-Za-z0-9_]*\s*[.:]\s*)?(?:%s)\s*\(" % "|".join(NIL_CAPABLE_CALLS)
NIL_CALL_BEFORE_OPERATOR = re.compile(CALL + r"[^()]*(?:\([^()]*\)[^()]*)*\)\s*(?:[-+*/%%])(?!=)")
NIL_CALL_AFTER_OPERATOR = re.compile(r"[-+*/%%]\s*" + CALL)


def run_nil_call_arithmetic_check(files):
    """No arithmetic directly on a call whose result may be nil.

    These helpers return nil for "not read yet" on purpose (so nothing gets moved based
    on a guessed capacity). Every caller has to test the value first, e.g.
    `local cap = self:slotCapacityFor(...) ; if cap then ... end`.
    """
    problems = []
    for rel, content in files:
        raw, _ = strip_lua_code(content)
        code = STRING_LITERAL.sub('""', raw)
        for index, line in enumerate(code.splitlines(), 1):
            if line.lstrip().startswith("--"):
                continue
            if NIL_CALL_BEFORE_OPERATOR.search(line) or NIL_CALL_AFTER_OPERATOR.search(line):
                problems.append("  %s:%d  %s" % (rel, index, line.strip()))
    if problems:
        raise SystemExit(
            "构建中止：直接对可能为 nil 的调用结果做算术（运行时会崩主控：attempt to perform "
            "arithmetic on a nil value）。\n"
            "这些函数在“还没读到”时返回 nil：%s。\n"
            "修法：先取到局部变量并判空，例如 local cap = self:slotCapacityFor(...) ; "
            "if cap then ... end：\n%s"
            % (", ".join(NIL_CAPABLE_CALLS), "\n".join(sorted(set(problems))))
        )
    print("nil 算术检查：通过（%d 个 Lua 文件，没有对可能为 nil 的调用结果直接做算术）"
          % len(files))
    return files


HARD_DEPENDENCY = re.compile(
    r"needs the ([a-z0-9_]+) module:\s*pass opts\.([A-Za-z0-9_]+)\s*\(loadModule\(\\?\"([a-z0-9_]+)\\?\"\)\)")
LOAD_MODULE_BINDING = re.compile(
    r"local\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*loadModule\(\s*\"([A-Za-z0-9_]+)\"\s*\)")
NEW_CALL = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*\.\s*new\s*\(")

def call_arguments(code, open_paren):
    depth = 0
    index = open_paren
    size = len(code)
    while index < size:
        char = code[index]
        if char in "\"'":
            index = scan_short_string(code, index)
            continue
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return code[open_paren + 1:index]
        index += 1
    return code[open_paren + 1:]

def hard_dependencies(files):
    required = {}
    for rel, content in files:
        name = os.path.splitext(os.path.basename(rel))[0]
        for match in HARD_DEPENDENCY.finditer(strip_comments(content)):
            pairs = required.setdefault(name, [])
            entry = (match.group(1), match.group(2))
            if entry not in pairs:
                pairs.append(entry)
    return required

def option_argument(key):
    return re.compile(r"(?<![A-Za-z0-9_])%s\s*=(?!=)" % re.escape(key))

def run_hard_dependency_check(files):
    required = hard_dependencies(files)
    if not required:
        print("硬依赖检查：通过（没有声明 \"needs the ... module\" 的模块）")
        return files
    problems = []
    injected = {}
    for rel, content in files:
        code = strip_comments(content)
        bindings = {}
        for match in LOAD_MODULE_BINDING.finditer(code):
            bindings[match.group(1)] = match.group(2)
        for match in NEW_CALL.finditer(code):
            variable = match.group(1)
            module_name = bindings.get(variable)
            if module_name is None or module_name not in required:
                continue
            arguments = call_arguments(code, match.end() - 1)
            line = code.count("\n", 0, match.start()) + 1
            for dep, key in required[module_name]:
                if option_argument(key).search(arguments):
                    injected[(module_name, dep)] = injected.get((module_name, dep), 0) + 1
                    continue
                problems.append("  %s:%d  %s.new(...) 没有注入 opts.%s"
                                "（%s.lua 里写着 \"needs the %s module\"）"
                                % (rel, line, variable, key, module_name, dep))
    for module_name in sorted(required):
        for dep, key in required[module_name]:
            if not injected.get((module_name, dep)):
                problems.append("  %s.lua 声明了 \"needs the %s module\"，"
                                "但没有任何 X.new(...) 构造点注入 opts.%s（装配漏了？）"
                                % (module_name, dep, key))
    if problems:
        raise SystemExit(
            "构建中止：模块声明了硬依赖，就必须在每个构造点显式注入对应的 opts 键。\n"
            "漏注入的后果是**后端一启动就 error**（模块里那条硬断言，不是可以兜底的业务状态）：\n"
            + "\n".join(problems)
            + "\n修法：在 loadModule(\"x\") 之后，构造语句里补上 `Key = X,`"
              "（例如 Dispatch.new({ Assert = Assert, Queue = Queue, ... })）")
    proof = ["%s->%s" % (name, dep) for name in sorted(required) for dep, _ in required[name]]
    print("硬依赖检查：通过（%d 个模块声明了硬依赖：%s；共 %d 个构造点都注入了 opts 键）"
          % (len(required), "、".join(proof), sum(injected.values())))
    return files

