# Lua 保留字不能当字段名 / 表键：`t.local = 1`、`{ local = 0 }` 都是 Lua 5.1 的语法错误
# （CC:T 会直接报 “unexpected symbol near 'local'”，而且这种错误只有真正 load 时才暴露）。
LUA_KEYWORDS = (
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function",
    "if", "in", "local", "nil", "not", "or", "repeat", "return", "then",
    "true", "until", "while",
)
KEYWORD_FIELD_PATTERNS = (
    ("字段访问 t.<关键字>", re.compile(r"\.\s*(%s)\b" % "|".join(LUA_KEYWORDS))),
    ("表键 { <关键字> =", re.compile(r"[,{]\s*(%s)\s*=" % "|".join(LUA_KEYWORDS))),
)
STRING_LITERAL = re.compile(r"\"(\\\\.|[^\"\\\\])*\"|'(\\\\.|[^'\\\\])*'")


# 实例字段把类方法遮蔽掉：`function Diagnose:perf()` 定义了方法 perf，
# 而 `diagnose.perf = <表>`（或同一文件里的 `self.perf = <表>`）会在实例上放一个同名字段；
# 之后 `obj:perf()` 就会报 “attempt to call method 'perf' (a table value)”。
METHOD_DEF = re.compile(r"^\s*function\s+([A-Za-z0-9_]+)\s*[:.]\s*([A-Za-z0-9_]+)\s*\(")
FIELD_ASSIGN = re.compile(r"^\s*([A-Za-z0-9_.]+)\s*\.\s*([A-Za-z0-9_]+)\s*=(?!=)")


def run_method_shadow_check(files):
    """检查“实例字段有没有把类方法遮蔽掉”（只有运行时才暴露，构建阶段先拦住）。"""
    methods, owners = {}, {}
    for rel, content in files:
        for line in content.splitlines():
            match = METHOD_DEF.match(line)
            if not match:
                continue
            class_name, method = match.group(1), match.group(2)
            methods.setdefault(class_name, set()).add(method)
            owners.setdefault(rel, set()).add(class_name)
    problems = []
    for rel, content in files:
        local_classes = owners.get(rel, set())
        for index, line in enumerate(content.splitlines(), 1):
            match = FIELD_ASSIGN.match(line.split("--")[0])
            if not match:
                continue
            target, field = match.group(1), match.group(2)
            last = target.split(".")[-1]
            if last == "self":
                candidates = local_classes
            else:
                candidates = set(name for name in methods if name.lower() == last.lower())
            for class_name in candidates:
                if field in methods.get(class_name, ()):
                    problems.append("  %s:%d  %s.%s 会覆盖 %s:%s()：%s" % (
                        rel, index, target, field, class_name, field, line.strip()[:90]))
    if problems:
        raise SystemExit(
            "构建中止：实例字段与类方法重名（运行时会报 attempt to call method 'x'）。\n"
            "请给字段改名（例如 perf -> perfStats、stats -> statsSummary）：\n" + "\n".join(problems)
        )
    print("方法遮蔽检查：通过（%d 个 Lua 文件，没有实例字段覆盖类方法）" % len(files))
    return files


# ===== 轻量 Lua 语法检查 =====
# 说明：这里不是完整的 Lua 解析器（本机没有 lua/luajit 可执行文件），
# 但能挡住“只有真正 load 时才报错”的几类常见错误：
#   1) `:` 方法调用却忘了写参数（Lua: function arguments expected / unexpected symbol）
#      —— 例如 `self:method and x`（正确写法是 `self.method and self:method()`）
#   2) 块结构不平衡（function/if/do/repeat 与 end/until 对不上，或提前多出一个 end）
#   3) 字符串没有收尾（换行前没闭合的 " 或 '）
LUA_METHOD_CALL = re.compile(r":\s*([A-Za-z_][A-Za-z_0-9]*)(?![A-Za-z_0-9])\s*(?![({}\"'])" + r"(?![A-Za-z_0-9])")


def strip_lua_code(content):
    """把注释、字符串、长括号替换成空格（保留换行），只留代码骨架；同时报告未闭合的字符串。"""
    out = []
    problems = []
    i = 0
    n = len(content)
    while i < n:
        match = re.match(r"\[(=*)\[", content[i:])
        if match:
            level = len(match.group(1))
            closer = "]" + "=" * level + "]"
            j = content.find(closer, i)
            j = n if j < 0 else j + len(closer)
            out.append("".join(" " if ch != "\n" else "\n" for ch in content[i:j]))
            i = j
            continue
        if content.startswith("--", i):
            j = content.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        ch = content[i]
        if ch in "\"'":
            j = i + 1
            terminated = False
            while j < n:
                if content[j] == "\\":
                    j += 2
                    continue
                if content[j] == ch:
                    terminated = True
                    j += 1
                    break
                if content[j] == "\n":
                    break
                j += 1
            if not terminated:
                problems.append(("string", content.count("\n", 0, i) + 1, content[i:i + 60].split("\n")[0]))
            out.append(" " * (j - i))
            i = j
            continue
        out.append(ch)
        i += 1
    return "".join(out), problems


def run_lua_structure_check(files):
    """轻量结构检查（luaparse 不可用时的退路）：方法调用参数 / 块结构 / 字符串收尾。"""
    problems = []
    for rel, content in files:
        code, string_problems = strip_lua_code(content)
        for _, number, text in string_problems:
            problems.append("  %s:%d  字符串没有收尾：%s" % (rel, number, text.strip()[:60]))
        for match in LUA_METHOD_CALL.finditer(code):
            number = code.count("\n", 0, match.start()) + 1
            problems.append("  %s:%d  `:%s` 后面缺少调用参数（Lua 会报 function arguments expected）：%s"
                            % (rel, number, match.group(1),
                               code.split("\n")[number - 1].strip()[:80]))
        depth = 0
        for number, line in enumerate(code.split("\n"), 1):
            for word in re.findall(r"[A-Za-z_][A-Za-z_0-9]*", line):
                if word in ("function", "if", "do", "repeat"):
                    depth += 1
                elif word in ("end", "until"):
                    depth -= 1
                    if depth < 0:
                        problems.append("  %s:%d  多出来的 `end`（块结构已经回到顶层）：%s"
                                        % (rel, number, line.strip()[:80]))
                        depth = 0
        if depth != 0:
            problems.append("  %s  块结构不平衡：还差 %d 个 `end`/`until`" % (rel, depth))
    if problems:
        raise SystemExit(
            "构建中止：Lua 语法检查发现问题（这些错误只有真正 load 时才会暴露）。\n"
            "常见修法：`self:foo and x` -> `self.foo and self:foo()`；补齐/删掉多余的 end。\n"
            + "\n".join(problems)
        )
    print("Lua 结构检查：通过（%d 个 Lua 文件：方法调用参数 / 块结构 / 字符串收尾；建议装 luaparse 做完整语法检查）"
          % len(files))
    return files


# ===== Lua 语法检查（用现成库 luaparse；Lua 5.1 文法 = CC:T 用的 Lua）=====
# luaparse 是一个纯 JS 的 Lua 解析器（npm install luaparse），比手写的结构检查严格得多：
# 任何语法错误都会带行号报出来，和 CC:T 里 load 的行为一致（同一个 Lua 5.1 文法）。
LUAPARSE_RUNNER = r"""
const fs = require('fs');
const luaparse = require('luaparse');
const entries = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
let problems = 0;
for (const entry of entries) {
    try {
        luaparse.parse(entry.code, { luaVersion: '5.1', locations: true, comments: false, scope: false });
    } catch (err) {
        problems += 1;
        const line = err.line === undefined ? '?' : err.line;
        const message = String(err.message || err).split('\n')[0];
        console.log('  ' + entry.rel + ':' + line + '  ' + message);
    }
}
process.exit(problems ? 1 : 0);
"""


LUAPARSE_LAST_ERROR = [""]      # 最近一次探测 luaparse 失败的原因（构建时打印出来）
LUAPARSE_ENV = [None]           # 探测成功时用的环境（带 NODE_PATH），语法检查步骤复用


def luaparse_env(base_dir):
    """构造“能 require 到 luaparse”的环境变量：优先仓库里的 backend/node_modules，
    其次是上一层与 npm 全局目录。必须把它同时交给探测与实际检查：
    检查脚本写在临时目录里（%TEMP%），Node 只按脚本所在目录向上找 node_modules，
    看不到 backend/node_modules —— 以前只有探测带了这个环境，于是“探测通过、检查却
    报 Cannot find module 'luaparse'”，构建莫名其妙中止（错误还在 stderr 里被吞掉）。"""
    import os as _os

    env = dict(_os.environ)
    extra = [_os.path.join(base_dir, "node_modules"), _os.path.join(_os.path.dirname(base_dir), "node_modules")]
    try:
        import subprocess
        root = subprocess.run(["npm", "root", "-g"], capture_output=True, text=True, timeout=60)
        if root.returncode == 0 and root.stdout.strip():
            extra.append(root.stdout.strip())
    except Exception:
        pass
    env["NODE_PATH"] = _os.pathsep.join([p for p in extra if p] + [env.get("NODE_PATH", "")])
    return env


def luaparse_available(base_dir):
    """本机是否装了 Node 模块 luaparse（在当前环境里 require 得到就算有）。
    顺便把失败原因记进 LUAPARSE_LAST_ERROR、把环境记进 LUAPARSE_ENV。"""
    import subprocess

    env = luaparse_env(base_dir)
    try:
        result = subprocess.run(
            ["node", "-e", "process.stdout.write(require.resolve('luaparse'))"],
            cwd=base_dir, capture_output=True, text=True, timeout=120, env=env)
        if result.returncode == 0:
            LUAPARSE_ENV[0] = env
            return True
        LUAPARSE_LAST_ERROR[0] = (result.stderr or result.stdout or "").strip().splitlines()[-1][:160]
        return False
    except Exception as err:
        LUAPARSE_LAST_ERROR[0] = str(err)[:160]
        return False


def run_lua_syntax_check(files, base_dir=None):
    """Lua 语法检查：优先用现成的 luaparse，缺库时退回到轻量结构检查。"""
    import json
    import os as _os
    import subprocess
    import tempfile

    base_dir = base_dir or BASE_DIR_HACK[0]
    if not luaparse_available(base_dir):
        print("提示：没有找到 Node 模块 luaparse（原因：%s）——执行 npm install --prefix backend luaparse "
              "可启用完整 Lua 语法检查；本次退回轻量结构检查。" % (LUAPARSE_LAST_ERROR[0] or "unknown"))
        return run_lua_structure_check(files)

    runner_path = _os.path.join(tempfile.gettempdir(), "ifm_luaparse_check.js")
    payload_path = _os.path.join(tempfile.gettempdir(), "ifm_luaparse_files.json")
    with open(runner_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(LUAPARSE_RUNNER)
    with open(payload_path, "w", encoding="utf-8") as handle:
        # 直接带上源码（构建时文件内容本来就在内存里），不依赖磁盘路径
        json.dump([{"rel": rel, "code": content} for rel, content in files], handle)
    try:
        result = subprocess.run(["node", runner_path, payload_path],
                                cwd=base_dir, capture_output=True, text=True, timeout=600,
                                env=LUAPARSE_ENV[0] or luaparse_env(base_dir))
    except Exception as err:
        print("提示：luaparse 调用失败（%s），退回轻量结构检查。" % err)
        return run_lua_structure_check(files)
    if result.returncode != 0:
        # 明细在 stdout；脚本自己挂掉（例如找不到模块）时 stdout 是空的，这时把 stderr 也带上，
        # 否则构建只报一句“语法检查失败”，完全看不出发生了什么（以前就吃过这个亏）。
        details = (result.stdout or "").strip() or (result.stderr or "").strip() or "(没有输出)"
        raise SystemExit(
            "构建中止：Lua 语法检查失败（luaparse，Lua 5.1 文法 = CC:T 用的 Lua）。\n"
            "这些错误在 CC:T 里 load 时同样会报，请按行号修好再构建：\n" + details)
    print("Lua 语法检查：通过（luaparse，%d 个文件）" % len(files))
    return files


# ===== 文件级 local 用在声明之前（运行时读到的是 nil 全局）=====
# 现场（用户报的真实故障）：`local stackScanStats = {...}` 原本写在文件 1400 行，
# 而 700 行的快照函数里先用了它 —— Lua 的 local 只从声明那行起生效，于是 700 行读到的是
# 一个不存在的全局（nil），快照推送整个抛错，网页上机器定义与外设信息全部消失。
# 这类错误 luaparse 查不出来（语法完全合法），只在运行时炸，所以在这里静态拦一道。
#
# 规则（刻意保守，宁可漏报也不要误报把构建卡住）：
#   * 只看**顶格**的 local 声明（`^local ...` / `^local function ...`）= 文件级状态；
#   * 名字如果在文件里任何位置当过**函数参数**或**for 循环变量**，就整体跳过
#     （那些在别的函数里同名，正则分辨不出作用域，跳过最安全）；
#   * 剩下的名字若在声明行之前就被当成表/函数用（name. / name[ / name( / name:），
#     就是真 bug —— Lua 会读到一个 nil 全局。
LOCAL_LIST_DECL = re.compile(r"^local\s+([A-Za-z_][A-Za-z_0-9]*(?:\s*,\s*[A-Za-z_][A-Za-z_0-9]*)*)\s*(?:=|$)",
                             re.MULTILINE)
LOCAL_FUNC_DECL = re.compile(r"^local\s+function\s+([A-Za-z_][A-Za-z_0-9]*)", re.MULTILINE)
FUNCTION_PARAMS = re.compile(r"\bfunction\b[^(\n]*\(([^)]*)\)")
FOR_VARIABLES = re.compile(r"^\s*for\s+(.+?)\s+(?:in\b|=)")
IDENTIFIER_ONLY = re.compile(r"^[A-Za-z_][A-Za-z_0-9]*$")


def collect_bound_names(content):
    """文件里出现过的函数参数名 / for 循环变量名（含 `for _, x in` 这种）。"""
    bound = set()
    code = STRING_LITERAL.sub('""', content)
    for match in FUNCTION_PARAMS.finditer(code):
        for name in match.group(1).split(","):
            name = name.strip()
            if IDENTIFIER_ONLY.match(name):
                bound.add(name)
    for match in FOR_VARIABLES.finditer(code):
        for name in match.group(1).split(","):
            name = name.strip()
            if IDENTIFIER_ONLY.match(name):
                bound.add(name)
    return bound


def run_local_order_check(files):
    """检查“顶格 local 在声明之前就被当成表/函数使用”（Lua 会当成全局，运行时是 nil）。"""
    problems = []
    for rel, content in files:
        lines = content.splitlines()
        bound = collect_bound_names(content)
        declarations = {}
        for index, line in enumerate(lines, 1):
            code = STRING_LITERAL.sub('""', line).split("--")[0]
            match = LOCAL_FUNC_DECL.match(code)
            if match:
                declarations.setdefault(match.group(1), index)
            match = LOCAL_LIST_DECL.match(code)
            if match:
                for name in match.group(1).split(","):
                    name = name.strip()
                    if name and name not in declarations:
                        declarations[name] = index
        for name, first in declarations.items():
            if name in bound:
                continue
            pattern = re.compile(r"(?<![A-Za-z0-9_.:])%s\s*[:.\[(]" % re.escape(name))
            for index, line in enumerate(lines, 1):
                if index >= first:
                    break
                code = STRING_LITERAL.sub('""', line).split("--")[0]
                if pattern.search(code):
                    problems.append("  %s:%d  先用后声明：`%s`（它到第 %d 行才 local）"
                                    % (rel, index, name, first))
                    break
    if problems:
        raise SystemExit(
            "构建中止：文件级局部变量在声明之前就被使用（Lua 会把它当全局，运行时是 nil：\n"
            "attempt to index global 'x' (a nil value)）。\n"
            "修法：把这个 local 声明挪到第一次使用之前（一般放在文件上方的状态区）：\n"
            + "\n".join(problems))
    print("定义顺序检查：通过（%d 个 Lua 文件，没有“先用后声明”的文件级局部变量）" % len(files))
    return files


def run_local_order_check(files):
    """检查“局部变量在声明之前被当成表/函数使用”。

    只关心文件里**确实存在 local 声明**的名字：它们一旦出现在声明行之前，
    Lua 会把那处当成全局变量（nil），运行时报 attempt to index/call global 'x'。
    """
    problems = []
    for rel, content in files:
        lines = content.splitlines()
        declarations = {}
        for index, line in enumerate(lines, 1):
            code = STRING_LITERAL.sub('""', line).split("--")[0]
            match = LOCAL_FUNC_DECL.match(code)
            if match:
                declarations.setdefault(match.group(1), []).append(index)
            match = LOCAL_LIST_DECL.match(code)
            if match:
                for name in match.group(1).split(","):
                    name = name.strip()
                    if name:
                        declarations.setdefault(name, []).append(index)
        for name, numbers in declarations.items():
            first = numbers[0]
            pattern = re.compile(r"(?<![A-Za-z0-9_.:])%s\s*[:.\[(]" % re.escape(name))
            for index, line in enumerate(lines, 1):
                if index >= first:
                    break
                code = STRING_LITERAL.sub('""', line).split("--")[0]
                if pattern.search(code):
                    problems.append("  %s:%d  先用后声明：`%s`（它到第 %d 行才 local）"
                                    % (rel, index, name, first))
                    break
    if problems:
        raise SystemExit(
            "构建中止：局部变量在声明之前就被使用（Lua 会把它当全局，运行时是 nil：\n"
            "attempt to index global 'x' (a nil value)）。\n"
            "修法：把这个 local 声明挪到第一次使用之前（一般放在文件上方的状态区）：\n"
            + "\n".join(problems))
    print("定义顺序检查：通过（%d 个 Lua 文件，没有“先用后声明”的局部变量）" % len(files))
    return files


